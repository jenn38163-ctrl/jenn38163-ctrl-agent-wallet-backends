import os
from typing import Text
from tfx.orchestration import pipeline
from tfx.orchestration.local.local_dag_runner import LocalDagRunner
from tfx.components import CsvExampleGen, StatisticsGen, SchemaGen, ExampleValidator
from tfx.orchestration.metadata import sqlite_metadata_connection_config

# This TFX pipeline demonstrates a Systemaccounting compliance and value flow analysis.
# It enforces "BIBO stability and dynamic equilibrium" by detecting anomalies in transaction records.

def create_pipeline(
    pipeline_name: Text,
    pipeline_root: Text,
    data_root: Text,
    metadata_path: Text,
) -> pipeline.Pipeline:
    
    # 1. Ingest Transaction JSONs (or CSV representations) generated by the Ledger
    example_gen = CsvExampleGen(input_base=data_root)

    # 2. Compute statistics over the conserved inputs (creditor/debitor value pairs)
    statistics_gen = StatisticsGen(examples=example_gen.outputs['examples'])

    # 3. Generate a schema enforcing the conservation law (value measured by seller - buyer = 0)
    schema_gen = SchemaGen(statistics=statistics_gen.outputs['statistics'], infer_feature_shape=False)

    # 4. Validate new transactions against the expected Systemaccounting Schema
    example_validator = ExampleValidator(
        statistics=statistics_gen.outputs['statistics'],
        schema=schema_gen.outputs['schema']
    )

    return pipeline.Pipeline(
        pipeline_name=pipeline_name,
        pipeline_root=pipeline_root,
        components=[
            example_gen,
            statistics_gen,
            schema_gen,
            example_validator,
        ],
        enable_cache=True,
        metadata_connection_config=sqlite_metadata_connection_config(metadata_path),
    )

if __name__ == '__main__':
    _pipeline_name = 'systemaccounting_value_flow'
    _pipeline_root = os.path.join(os.environ['HOME'], 'tfx', 'pipelines', _pipeline_name)
    _metadata_path = os.path.join(os.environ['HOME'], 'tfx', 'metadata', _pipeline_name, 'metadata.db')
    _data_root = os.path.join(os.path.dirname(__file__), 'data')
    
    os.makedirs(_data_root, exist_ok=True)
    with open(os.path.join(_data_root, 'transactions.csv'), 'w') as f:
        f.write("item,price,quantity,creditor,debitor\nbottled water,1.000,1,GroceryStore,JacobWebb\n")

    LocalDagRunner().run(
        create_pipeline(
            pipeline_name=_pipeline_name,
            pipeline_root=_pipeline_root,
            data_root=_data_root,
            metadata_path=_metadata_path
        )
    )
